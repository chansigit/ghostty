import Foundation
import GhosttyKit

/// A single user-defined trigger. See the `trigger` config option.
struct TriggerItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var name: String = ""
    /// Oniguruma regular expression matched against the text before the cursor.
    var regex: String = ""
    /// Text to send, using the config escapes (\n, \r, \t, \\, \xNN).
    var text: String = ""
    var enabled: Bool = true

    /// Why Ghostty would reject this trigger, if it would. Such a trigger is
    /// left out of the generated config instead of failing silently there.
    var problem: String? {
        if regex.contains("=>") { return "The regular expression can't contain \"=>\"." }
        var chars = text.makeIterator()
        while let c = chars.next() {
            guard c == "\\" else { continue }
            switch chars.next() {
            case "n", "r", "t", "\\", "'", "\"":
                continue
            case "x":
                guard let a = chars.next(), let b = chars.next(), a.isHexDigit, b.isHexDigit else {
                    return "\\x must be followed by two hex digits."
                }
            case "u":
                // \u{...}
                guard chars.next() == "{" else { return "\\u must look like \\u{1F600}." }
                var closed = false
                while let h = chars.next() {
                    if h == "}" { closed = true; break }
                    if !h.isHexDigit { return "\\u must look like \\u{1F600}." }
                }
                if !closed { return "\\u must look like \\u{1F600}." }
            default:
                return "Unknown escape in the text. Use \\\\ for a backslash."
            }
        }
        return nil
    }
}

/// Persists triggers. The JSON file is the source of truth for the GUI and
/// we generate `triggers.ghostty` (enabled triggers only) next to the main
/// config file, which is pulled in with a `config-file` line.
final class TriggerStore: ObservableObject {
    @Published var items: [TriggerItem] = []

    static let includeLine = "config-file = ?triggers.ghostty"

    private let configDir: URL

    init() {
        let path = Ghostty.AllocatedString(ghostty_config_open_path()).string
        if path.isEmpty {
            configDir = FileManager.default.homeDirectoryForCurrentUser
                .appendingPathComponent(".config/ghostty")
        } else {
            configDir = URL(fileURLWithPath: path).deletingLastPathComponent()
        }
        load()
    }

    private var jsonURL: URL { configDir.appendingPathComponent("triggers.json") }
    private var generatedURL: URL { configDir.appendingPathComponent("triggers.ghostty") }
    private var mainConfigURL: URL {
        let path = Ghostty.AllocatedString(ghostty_config_open_path()).string
        return path.isEmpty ? configDir.appendingPathComponent("config.ghostty") : URL(fileURLWithPath: path)
    }

    func load() {
        guard let data = try? Data(contentsOf: jsonURL),
              let decoded = try? JSONDecoder().decode([TriggerItem].self, from: data) else { return }
        items = decoded
    }

    /// Write the JSON and the generated config, and make sure the main
    /// config includes the generated file.
    func save() throws {
        let fm = FileManager.default
        try fm.createDirectory(at: configDir, withIntermediateDirectories: true)

        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        try writePrivate(try encoder.encode(items), to: jsonURL)

        var lines = ["# Generated by Ghostty's Triggers window. Edits will be overwritten."]
        for item in items where item.enabled && item.problem == nil && !item.regex.isEmpty {
            // Values are wrapped in quotes so surrounding whitespace is kept.
            // Newlines can't be represented on one line.
            let regex = item.regex.replacingOccurrences(of: "\n", with: "")
            let text = item.text.replacingOccurrences(of: "\n", with: "\\n")
            lines.append("trigger = \"\(regex)=>\(text)\"")
        }
        try writePrivate(Data((lines.joined(separator: "\n") + "\n").utf8), to: generatedURL)

        try ensureIncluded()
    }

    /// Replace a file that can hold passwords. It is created owner-only
    /// rather than tightened after the fact, and a symlink is written
    /// through instead of being replaced by a regular file.
    private func writePrivate(_ data: Data, to url: URL) throws {
        let fm = FileManager.default
        let dest = url.resolvingSymlinksInPath()
        let tmp = dest.deletingLastPathComponent()
            .appendingPathComponent(".\(dest.lastPathComponent).\(UUID().uuidString).tmp")
        guard fm.createFile(atPath: tmp.path, contents: data, attributes: [.posixPermissions: 0o600]) else {
            throw CocoaError(.fileWriteUnknown)
        }
        do {
            if fm.fileExists(atPath: dest.path) {
                _ = try fm.replaceItemAt(dest, withItemAt: tmp)
            } else {
                try fm.moveItem(at: tmp, to: dest)
            }
        } catch {
            try? fm.removeItem(at: tmp)
            throw error
        }
        // Replacing keeps the old file's permissions, which may be wider.
        try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: dest.path)
    }

    private func ensureIncluded() throws {
        let url = mainConfigURL
        let existing = (try? String(contentsOf: url, encoding: .utf8)) ?? ""
        let already = existing.split(separator: "\n").contains {
            $0.trimmingCharacters(in: .whitespaces) == Self.includeLine
        }
        if already { return }
        // Append in place: the user's config may be a symlink into a
        // dotfiles repo, and its permissions are theirs to choose.
        var addition = "\n# Added by Ghostty's Triggers window.\n\(Self.includeLine)\n"
        if !existing.isEmpty && !existing.hasSuffix("\n") { addition = "\n" + addition }
        let dest = url.resolvingSymlinksInPath()
        if !FileManager.default.fileExists(atPath: dest.path) {
            FileManager.default.createFile(atPath: dest.path, contents: nil)
        }
        let handle = try FileHandle(forWritingTo: dest)
        defer { try? handle.close() }
        try handle.seekToEnd()
        try handle.write(contentsOf: Data(addition.utf8))
    }
}
